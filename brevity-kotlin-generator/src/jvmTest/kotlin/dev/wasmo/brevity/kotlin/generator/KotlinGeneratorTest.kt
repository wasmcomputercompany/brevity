class KotlinGeneratorTest {
  private fun tester(): BrevityTester {
    val tester = BrevityTester(
      "clock.wit".toPath() to
        """
        package wasi:clocks@0.2.12;

        /// gets the epoch time
        @since(version = 0.2.0)
        interface types {
            /// A time and date in seconds plus nanoseconds.
            @since(version = 0.2.0)
            record datetime {
                /// Since 1970.
                seconds: u64,
                /// Always less than 1000000000.
                nanoseconds: u32,
            }

            /// Read the current value of the clock.
            @since(version = 0.2.0)
            now: func() -> datetime;

            /// `pollable` represents a single I/O event which may be ready, or not.
            resource pollable {
                /// Return the readiness of a pollable. This function never blocks.
                ready: func() -> bool;
            }

            /// Lookup error codes.
            variant error-code {
                /// Access denied.
                access-denied,
                /// A catch-all.
                other(option<string>),
            }

            /// File or memory access pattern advisory information.
            enum advice {
                /// No advice.
                normal,
                /// sequentially from lower to higher.
                sequential,
            }

            /// How paths are resolved.
            flags path-flags {
                /// Follow the darn things.
                symlink-follow,
            }

            /// You can do both with an epoch.
            type instant = datetime;
        }
        """.trimIndent(),

      "world.wit".toPath() to
        """
        package wasi:clocks@0.2.12;

        world time {
            import types;

            /// Execute the command and return an exit code.
            export run: func(
                /// command-line arguments.
                args: list<string>
            ) -> s32;
        }
        """.trimIndent(),
    )

    assertThat(tester.files).hasSize(8)
    return tester
  }

