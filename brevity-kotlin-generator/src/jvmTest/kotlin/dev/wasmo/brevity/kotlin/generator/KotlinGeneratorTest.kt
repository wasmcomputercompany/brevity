  @Test
  fun `world host`() {
    assertThat(tester()["wit/wasi/clocks/v0_2_12/TimeHost.kt".toPath()]).isEqualTo(
      """
      // Generated by Brevity. Do not edit.
      //   world.wit
      @file:OptIn(BrevityInternalApi::class)

      package wit.wasi.clocks.v0_2_12

      import com.dylibso.chicory.runtime.ExportFunction
      import com.dylibso.chicory.runtime.HostFunction
      import com.dylibso.chicory.runtime.Instance
      import com.dylibso.chicory.runtime.Store
      import com.dylibso.chicory.runtime.WasmFunctionHandle
      import com.dylibso.chicory.wasm.types.FunctionType
      import com.dylibso.chicory.wasm.types.ValType
      import dev.wasmo.brevity.BrevityInternalApi
      import dev.wasmo.brevity.HostBridge
      import dev.wasmo.brevity.World
      import kotlin.Int
      import kotlin.OptIn
      import kotlin.String
      import kotlin.collections.List
      import kotlin.text.encodeToByteArray

      public fun Time.World(hostFactory: (Time.Guest) -> Time.Host): World<Time.Host, Time.Guest> {
        val world = HostTime()
        world.host = hostFactory(world.guest)
        return world
      }

      internal class HostTime() : World<Time.Host, Time.Guest>() {
        private lateinit var bridge: HostBridge

        override lateinit var host: Time.Host

        override val guest: Time.Guest = RealGuest()

        internal lateinit var run_export: ExportFunction

        override fun initExports(instance: Instance) {
          this.run_export = instance.export("run")
        }

        override fun initImports(bridge: HostBridge, store: Store) {
          this.bridge = bridge
          store.addFunction(
            HostFunction(
              "wasi:clocks/types@0.2.12",
              "now",
              FunctionType.of(
                listOf(ValType.I32),
                listOf(),
              ),
              WasmFunctionHandle { instance, args ->
                val resultParameter = args[0].toInt()
                val result = host.clocksTypes.now()
                storeClocksTypesDatetimeImport(resultParameter, result)
                return@WasmFunctionHandle longArrayOf()
              },
            )
          )
          store.addFunction(
            HostFunction(
              "wasi:clocks/types@0.2.12",
              "[resource-drop]pollable",
              FunctionType.of(
                listOf(ValType.I32),
                listOf(),
              ),
              WasmFunctionHandle { instance, args ->
                // TODO: AbiResourceDropLift
                return@WasmFunctionHandle longArrayOf()
              },
            )
          )
          store.addFunction(
            HostFunction(
              "wasi:clocks/types@0.2.12",
              "[method]pollable.ready",
              FunctionType.of(
                listOf(ValType.I32),
                listOf(ValType.I32),
              ),
              WasmFunctionHandle { instance, args ->
                val rep_ = args[0].toInt()
                val receiver_ = bridge.getImportedResource<Pollable>(rep_)
                val result = receiver_.ready()
                val result_ = (if (result) 1 else 0)
                return@WasmFunctionHandle longArrayOf(result_.toLong())
              },
            )
          )
          store.addFunction(
            HostFunction(
              "wasi:clocks/types@0.2.12",
              "[dtor]pollable",
              FunctionType.of(
                listOf(ValType.I32),
                listOf(),
              ),
              WasmFunctionHandle { instance, args ->
                val rep_ = args[0].toInt()
                val receiver_ = bridge.getImportedResource<Pollable>(rep_)
                receiver_.close()
                return@WasmFunctionHandle longArrayOf()
              },
            )
          )
        }

        public fun storeClocksTypesDatetimeImport(address: Int, value_: Datetime) {
          bridge.memory.writeLong(address, value_.seconds.toLong())
          bridge.memory.writeI32(address + 8, value_.nanoseconds.toInt())
        }

        internal inner class RealGuest : Time.Guest {
          override fun run(args: List<String>): Int {
            val result = bridge.memoryAllocator.let { memoryAllocator ->
              val listAddress = memoryAllocator.allocate(args.size * 8)
              for (i in args.indices) {
                val elementAddress = listAddress + i * 8
                val byteArray = args[i].encodeToByteArray()
                val stringAddress = memoryAllocator.allocate(byteArray.size)
                bridge.memory.write(stringAddress, byteArray)
                val stringAddress_ = stringAddress
                val stringByteCount = byteArray.size
                bridge.memory.writeI32(elementAddress, stringAddress_)
                bridge.memory.writeI32(elementAddress + 4, stringByteCount)
              }
              val resultArray = run_export.apply(
                listAddress.toLong(),
                args.size.toLong(),
              )
              resultArray[0].toInt()
            }
            return result
          }
        }
      }

      """.trimIndent(),
    )
  }

